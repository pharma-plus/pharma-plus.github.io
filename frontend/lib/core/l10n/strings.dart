  /// Traduction simple. Ne pas traduire les paramètres enveloppés `{}` en
  /// le remplaçant : utilisez [format] pour l'interpolation.
  static String t(String key, String locale) =>
      _strings[locale]?[key] ?? _strings['fr']?[key] ?? key;

  static String format(String key, String locale, [Map<String, Object>? args]) {
    var value = t(key, locale);
    args?.forEach((k, v) {
      value = value.replaceAll('{$k}', '$v');
    });
    return value;
  }

